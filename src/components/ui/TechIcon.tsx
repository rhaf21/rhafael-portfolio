function normalize(name: string): string {
  return name.toLowerCase().trim();
}

export function getTechIcon(name: string): IconSpec | null {
  const key = normalize(name);
  if (ICONS[key]) return ICONS[key];
  // partial match for compound names like "React & Next.js"
  for (const k of Object.keys(ICONS)) {
    if (key.includes(k) && k.length >= 3) return ICONS[k];
  }
  return null;
}

export function TechIcon({ name, size = 22, className }: TechIconProps) {
  const icon = getTechIcon(name);
  if (!icon) return null;

  return (
    <svg
      width={size}
      height={size}
      viewBox={icon.viewBox ?? "0 0 24 24"}
      fill="currentColor"
      aria-hidden
      className={className}
    >
      {icon.paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}
